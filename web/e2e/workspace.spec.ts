import { expect, test } from '@playwright/test'

test('opens the approved proposal with its review and figures, and preserves historical topic evidence', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.summary-card')).toHaveCount(3)
  const summary = await page.locator('.research-summary').boundingBox()
  expect(summary!.y + summary!.height).toBeLessThan(page.viewportSize()!.height)
  await expect(page.locator('.research-summary table')).toHaveCount(0)
  await expect(page.locator('.stage-tag')).toContainText('提案 v0.4 通过审核')
  await expect(page.locator('.question-card')).toHaveCount(0)
  await page.getByRole('link', { name: '阅读提案', exact: true }).click()
  await expect(page).toHaveURL('/documents/PROPOSAL')
  await expect(page.locator('.markdown-body img')).toHaveCount(2)
  for (const image of await page.locator('.markdown-body img').all()) {
    await expect(image).toBeVisible()
    await expect.poll(() => image.evaluate((node: HTMLImageElement) => node.naturalWidth)).toBeGreaterThan(0)
  }
  await page.getByRole('link', { name: '研究者审核记录', exact: true }).click()
  await expect(page).toHaveURL('/documents/RESEARCH#decisions')
  await expect(page.locator('details#decisions').getByRole('row', { name: /v0\.4 内容审核/ })).toContainText('列为通过审核')
  await page.goto('/questions')
  await expect(page.getByRole('heading', { name: '历史问题', exact: true })).toBeVisible()
  const firstTopic = '/questions/D03'
  await page.getByRole('link', { name: '打开题卡', exact: true }).first().click()
  await expect(page).toHaveURL(firstTopic)
  await expect(page.getByRole('heading', { name: '历史题卡', exact: true })).toBeVisible()
  await expect(page.locator('.question-diagram svg')).toBeVisible({ timeout: 30_000 })
  await expect(page.locator('.question-diagram')).toContainText('待验证草案')
  await expect(page.locator('.question-evidence')).toContainText('替代解释')
  await expect(page.locator('.full-question .markdown-body')).not.toBeVisible()
  await page.getByRole('button', { name: '完整题卡：来源、假设、基线与停止条件' }).click()
  await expect(page.locator('.full-question .markdown-body')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('link', { name: '历史问题', exact: true })).toHaveAttribute('aria-current', 'page')
  await expect(page.locator('.question-diagram svg')).toBeVisible({ timeout: 30_000 })
  await page.getByRole('link', { name: '在历史存档中查看原文' }).click()
  await expect(page).toHaveURL(/archive%2Fpre-v04%2FRESEARCH#d03$/)
  await expect(page.locator('details#directions-current')).toHaveAttribute('open', '')
  const id = firstTopic!.split('/').at(-1)!.toLowerCase()
  await expect(page.locator('.markdown-body h3').filter({ hasText: new RegExp('^' + id.toUpperCase() + ' ·') })).toBeInViewport()
  await page.goto('/questions')
  await page.getByText('其他分组与历史', { exact: true }).click()
  const other = page.locator('.other-questions .question-links a').first()
  const otherUrl = await other.getAttribute('href')
  await other.click()
  await expect(page).toHaveURL(otherUrl!)
  await expect(page.locator('.question-detail h2')).toContainText(otherUrl!.split('/').at(-1)!)
  await page.goto('/questions/D99')
  await expect(page.getByText('没有找到这项问题', { exact: true })).toBeVisible()
})

test('reads evidence, searches documents, follows source links and renders diagrams', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '研究总览', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '查看证据状态' }).click()
  await expect(page.getByRole('dialog', { name: '证据状态' }).getByRole('link', { name: '同任务的高层战略采样' })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '搜索研究内容' }).click()
  await page.getByRole('textbox', { name: '搜索研究内容' }).fill('Planner')
  await page.locator('.search-result').filter({ has: page.locator('strong').filter({ hasText: /^研究工作台/ }) }).click()
  await expect(page).toHaveURL(/\/documents\/RESEARCH$/)
  await page.locator('details#decisions > summary').click()
  await page.getByRole('link', { name: 'README', exact: true }).click()
  await expect(page).toHaveURL(/\/documents\/README$/)
  await expect(page.getByRole('heading', { name: '研究设置', exact: true })).toBeVisible()
  await expect(page.locator('.mermaid-diagram svg')).toBeVisible({ timeout: 30_000 })
  await page.reload()
  await expect(page.getByRole('heading', { name: '研究设置', exact: true })).toBeVisible()
  await page.locator('.markdown-body summary').filter({ hasText: /^版本规则与当前配置$/ }).click()
  await page.getByRole('link', { name: '研究任务', exact: true }).click()
  await expect(page.getByRole('heading', { name: '研究任务模板', level: 1 })).toBeVisible()
  await expect(page.locator('.markdown-body pre code')).toContainText('验收与停止条件')
  expect(errors).toEqual([])
  await page.goto('/')
  await page.screenshot({ path: '/tmp/planner-workspace-desktop.png', fullPage: true })
})
